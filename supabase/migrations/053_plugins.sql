-- =========================================================
-- MIGRATION 053: Plugins and Third-Party Widgets Table
-- =========================================================

-- 1. Create plugins table
create table if not exists public.plugins (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  code text not null,
  slot text not null default 'home-top',
  position integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint plugins_slot_check check (slot in ('home-top', 'home-middle', 'home-bottom'))
);

-- 2. Indexes for efficient slot querying and admin sorting
create index if not exists idx_plugins_slot_active_pos on public.plugins (slot, active, position asc);
create index if not exists idx_plugins_created_at on public.plugins (created_at desc);

-- 3. Enable Row Level Security (RLS)
alter table public.plugins enable row level security;

-- 4. RLS Policies
-- Public (anonymous + authenticated) can only read active plugins
drop policy if exists "Public can view active plugins" on public.plugins;
create policy "Public can view active plugins"
  on public.plugins
  for select
  to anon, authenticated
  using (active = true);

-- Staff/Admin can view all plugins (both active and inactive) in admin views
drop policy if exists "Staff can view all plugins" on public.plugins;
create policy "Staff can view all plugins"
  on public.plugins
  for select
  to authenticated
  using (public.is_staff());

-- Staff/Admin can insert, update, and delete plugins via authenticated admin session
drop policy if exists "Staff can insert plugins" on public.plugins;
create policy "Staff can insert plugins"
  on public.plugins
  for insert
  to authenticated
  with check (public.is_staff());

drop policy if exists "Staff can update plugins" on public.plugins;
create policy "Staff can update plugins"
  on public.plugins
  for update
  to authenticated
  using (public.is_staff())
  with check (public.is_staff());

drop policy if exists "Staff can delete plugins" on public.plugins;
create policy "Staff can delete plugins"
  on public.plugins
  for delete
  to authenticated
  using (public.is_staff());

-- 5. Updated_at auto-touch trigger
create or replace function public.touch_plugins_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_plugins_updated_at on public.plugins;
create trigger trg_plugins_updated_at
  before update on public.plugins
  for each row execute function public.touch_plugins_updated_at();
